// ============================================================
// 外星信号 · 关卡图案（纯数据）：每幅图是一组等长字符串，字符 → 像素值
//   '.' = 0（暗）  '#' = 1（青）  '+' = 2（粉）  '*' = 3（金）
// 图案尺寸都选「两个质数之积」：reshape 的行列数只有唯一的有意义答案。
// ============================================================

const CHAR = { '.': 0, '#': 1, '+': 2, '*': 3 };

/** 字符画 → 二维整数数组（行 × 列），并校验每行等长 */
export function parseArt(rows) {
  const w = rows[0].length;
  return rows.map((r, i) => {
    if (r.length !== w) throw new Error(`第 ${i} 行长度 ${r.length} ≠ ${w}`);
    return [...r].map((c) => {
      if (!(c in CHAR)) throw new Error(`未知字符 ${c}`);
      return CHAR[c];
    });
  });
}

